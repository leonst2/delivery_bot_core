// Writes the shared arc test vectors to stdout. The output is committed as test/vectors/arc_vectors.txt; the C++
// test (test_vectors.cpp) and the Rust port (rust/tests/vectors.rs) both recompute every record from its inputs and
// compare with the expected values, so the two implementations can't drift apart.
//
// Regenerate (only when the formulas change on purpose):
//   build/delivery_bot_geometry/generate_arc_vectors > src/delivery_bot_core/delivery_bot_geometry/test/vectors/arc_vectors.txt

#include <cstdio>
#include <vector>

#include "delivery_bot_geometry/angle.hpp"
#include "delivery_bot_geometry/arc.hpp"
#include "delivery_bot_geometry/path.hpp"
#include "delivery_bot_geometry/se2.hpp"
#include "test_util.hpp"

namespace dbg = delivery_bot_geometry;

namespace
{

constexpr double kRadius = 1.25;
constexpr double kNoLimit = 1e9;  // "no upper window limit" (the text format has no infinity)

void print(double value) { std::printf(" %.17g", value); }

void print(const dbg::Pose2 & pose)
{
  print(pose.x);
  print(pose.y);
  print(pose.yaw);
}

void print_path(const dbg::Path & path)
{
  std::printf("path");
  print(path.start());
  std::printf(" %zu", path.segments().size());
  for (const auto & seg : path.segments()) {
    print(seg.curvature);
    print(seg.length);
  }
  std::printf("\nlength");
  print(path.length());
  std::printf("\n");
}

}  // namespace

int main()
{
  using S = dbg::Segment;
  dbg::test::RandomPoses rng(2024);

  std::printf(
    "# delivery_bot_geometry arc test vectors, generated by test/generate_arc_vectors.cpp. Do not edit.\n"
    "# Records (whitespace-separated, angles in rad, lengths in m):\n"
    "#   normalize a | expected\n"
    "#   compose ax ay ayaw bx by byaw | x y yaw\n"
    "#   inverse x y yaw | x y yaw\n"
    "#   advance x y yaw curvature length | x y yaw\n"
    "#   path x y yaw n (curvature length){n}     (the records below refer to the latest path)\n"
    "#   length | total\n"
    "#   pose_at s | x y yaw\n"
    "#   closest px py s_min s_max | s x y yaw distance\n"
    "#   track rx ry ryaw s_min s_max | s cross_track heading\n");

  for (int i = 0; i < 40; ++i) {
    const double a = rng.uniform(-20.0, 20.0);
    std::printf("normalize");
    print(a);
    print(dbg::normalize_angle(a));
    std::printf("\n");
  }
  for (int i = 0; i < 40; ++i) {
    const dbg::Pose2 a = rng.pose(10.0);
    const dbg::Pose2 b = rng.pose(10.0);
    std::printf("compose");
    print(a);
    print(b);
    print(a * b);
    std::printf("\ninverse");
    print(a);
    print(a.inverse());
    std::printf("\n");
  }
  for (int i = 0; i < 60; ++i) {
    const dbg::Pose2 p = rng.pose(10.0);
    // Include straight and nearly straight segments (the sinc series branch).
    double k = 0.0;
    if (i % 6 == 1) {
      k = rng.uniform(-1e-6, 1e-6);
    } else if (i % 6 != 0) {
      k = rng.uniform(-0.8, 0.8);
    }
    const double l = rng.uniform(-4.0, 4.0);
    std::printf("advance");
    print(p);
    print(k);
    print(l);
    print(dbg::advance(p, k, l));
    std::printf("\n");
  }

  std::vector<dbg::Path> paths{
    dbg::Path({0.0, 0.0, 0.0}, {S::straight(5.0)}),
    dbg::Path({1.0, 2.0, 0.4}, {S::left(2.0, kRadius), S::right(2.0, kRadius)}),
    dbg::Path({0.0, 0.0, 0.0}, {S::straight(2.0), S::left(-1.5, kRadius), S::straight(1.0)}),
    dbg::Path({-1.0, 0.0, 1.0}, {S::left(dbg::kTwoPi * kRadius * 1.3, kRadius)}),
    dbg::Path({0.0, 0.0, -2.0}, {S::right(-2.5, kRadius), S::straight(-1.0), S::left(0.8, 2.0 * kRadius)}),
  };
  for (int i = 0; i < 5; ++i) {
    std::vector<S> segments;
    segments.reserve(4);
    for (int k = 0; k < 4; ++k) {
      segments.push_back({rng.uniform(-0.8, 0.8), rng.uniform(-2.0, 2.0)});
    }
    paths.emplace_back(rng.pose(5.0), segments);
  }

  for (const auto & path : paths) {
    print_path(path);
    for (int i = 0; i < 12; ++i) {
      const double s = rng.uniform(-0.5, path.length() + 0.5);
      std::printf("pose_at");
      print(s);
      print(dbg::point_at(path, s));
      std::printf("\n");
    }
    for (int i = 0; i < 25; ++i) {
      const Eigen::Vector2d p = rng.pose(6.0).position();
      double lo = 0.0;
      double hi = kNoLimit;
      if (i % 2 == 1) {
        lo = rng.uniform(-0.5, path.length());
        hi = lo + rng.uniform(0.0, 2.0);
      }
      const auto c = dbg::closest_point(path, p, lo, hi);
      std::printf("closest");
      print(p.x());
      print(p.y());
      print(lo);
      print(hi);
      print(c.s);
      print(c.pose);
      print(c.distance);
      std::printf("\n");
    }
    for (int i = 0; i < 15; ++i) {
      const double s = rng.uniform(0.0, path.length());
      const dbg::Pose2 robot = path.pose_at(s) * dbg::Pose2(rng.uniform(-0.2, 0.2), rng.uniform(-0.3, 0.3), 0.2);
      const double lo = s - 0.3;
      const double hi = s + 0.3;
      const auto e = dbg::tracking_error(path, robot, lo, hi);
      std::printf("track");
      print(robot);
      print(lo);
      print(hi);
      print(e.s);
      print(e.cross_track);
      print(e.heading);
      std::printf("\n");
    }
  }
  return 0;
}
